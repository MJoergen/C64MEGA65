#!/usr/bin/env python3
"""Generate a simulation stand-in for a VHDL entity (NTSC work, issue #181).

    w2_standin.py SRC.vhd ENTITY OUT.vhd [--retype-in-ranged] [--retype PORT=TYPE ...]

Copies the context clause and the entity declaration of ENTITY from SRC.vhd and
adds an empty architecture "standin". Used by CORE/vhdl/test/tb_ntsc/run_w2.sh
for the av_pipeline elaboration bench (tb_window_av.vhd), where ghdl cannot
elaborate some sub-entities that are not under test:

  * ghdl refuses to associate an unconstrained integer actual with a ranged
    natural port ("bounds or direction of actual don't match"); digital_pipeline
    does that for ascal (htotal, hmin, ...) and for video_overlay
    (vga_cfg_shift_i). Synthesis accepts it. --retype-in-ranged turns every
    "IN natural RANGE a TO b" port into "IN integer", --retype changes one port.
  * the shared unisim stub has no OSERDESE2, so serialiser_10to1_selectio is
    replaced as a whole.

The stand-in keeps every generic and port name, so the instantiating file is
analyzed and elaborated unchanged.
"""

import re
import sys


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    src, name, out = sys.argv[1], sys.argv[2], sys.argv[3]
    opts = sys.argv[4:]
    text = open(src, errors="replace").read()
    m = re.search(r"^\s*entity\s+%s\s+is\b" % re.escape(name), text, re.I | re.M)
    if not m:
        print("entity %s not found in %s" % (name, src))
        return 1
    e = re.search(r"\bend\s+(entity\s+)?(%s\s*)?;" % re.escape(name), text[m.start():], re.I)
    ent = text[m.start():m.start() + e.end()]
    # context clause: library / use lines in front of the entity
    ctx = "\n".join(l for l in text[:m.start()].splitlines()
                    if re.match(r"\s*(library|use)\b", l, re.I))
    retyped = 0
    i = 0
    while i < len(opts):
        o = opts[i]
        if o == "--retype-in-ranged":
            ent, n = re.subn(r"(:\s*in\s+)natural\s+range\s+\d+\s+to\s+\d+", r"\1integer", ent, flags=re.I)
            retyped += n
        elif o == "--retype":
            port, typ = opts[i + 1].split("=")
            ent, n = re.subn(r"(\b%s\s*:\s*in\s+)[\w ]+?(\s*(:=[^;]*)?;)" % re.escape(port),
                             r"\g<1>%s\2" % typ, ent, flags=re.I)
            if n != 1:
                print("port %s not found" % port)
                return 1
            retyped += n
            i += 1
        i += 1
    with open(out, "w") as f:
        f.write("-- generated by doc/dev-ntsc/tools/w2_standin.py from %s (simulation stand-in)\n" % src)
        f.write(ctx + "\n\n" + ent + "\n\narchitecture standin of %s is\nbegin\nend architecture standin;\n" % name)
    print("stand-in %s: %d port(s) retyped" % (name, retyped))
    return 0


if __name__ == "__main__":
    sys.exit(main())
