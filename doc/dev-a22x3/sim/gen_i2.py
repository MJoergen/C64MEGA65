#!/usr/bin/env python3
"""
Writes scenarios/i2.stim next to this script: the scenario of the switches
"MEGA+left = right" of the submenu Mouse (see the header of the scenario). The
scenario repeats the same key pattern many times, so it is generated: change this
script and run it again instead of editing i2.stim.

    gen_i2.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# key codes of the scenario command "press", as in the other scenarios
K = {"Up": "0001", "Down": "0002", "Left": "0004", "Right": "0008", "Return": "0010",
     "Space": "0020", "Run/Stop": "0040", "Help": "0080"}
out = []


def key(k, dump=None):
    """Hold the key 3 ms, wait for 20 ms without UART or video RAM activity, optionally dump."""
    out.append("press %s 3" % K[k])
    out.append("wait_quiet 20000 500")
    if dump:
        out.append("dump " + dump)


def mark(t):
    out.append("mark " + t)


def help_open(dump):
    out.append("press 0080 3")
    out.append("wait_osm 1 300")
    out.append("wait_quiet 20000 500")
    out.append("dump " + dump)


def help_close(dump):
    out.append("press 0080 3")
    out.append("wait_osm 0 300")
    out.append("wait_quiet 20000 500")
    out.append("dump " + dump)
    out.append("# HELP_MENU ends with WAIT333MS (busy loop): the main loop reads keys again only after it")
    out.append("wait_ms 400")

hdr = """# Scenario i2: the switches MEGA+left = right of the submenu Mouse (issue #190), SD card
# sd/card_full.blk in the bottom tray. Generated by gen_i2.py: change the generator and run it
# again instead of editing this file. Each switch is a single-select item directly behind
# Port n: Amiga and is only visible while that item is selected; a hidden switch keeps its state.
# Every key: hold it 3 ms, then wait until neither the UART nor the video RAM was active for
# 20 ms. Menu bits = flat indices: Port 1: C64 / Amiga 308/309, switch of port 1 310, Port 2:
# C64 / Amiga 312/313, switch of port 2 314, Back of Mouse 316, opener Mouse 305.
# Visibility states of the switches: none, port 1 only, both, port 2 only; each is left once
# with Back and once with Run/Stop.
#   A  Help; Right, Up, Up, Return: Advanced Settings; Right, Up, Up, Return: Mouse (no switch);
#      Right, Return: Back; Return: Mouse; Run/Stop; Return: Mouse; Left, Down, Space: Port 1:
#      Amiga (switch 1 appears, off); Down: switch 1; Space: on; Return: off; Return: on;
#      Right, Return: Back; Return; Run/Stop; Return; Right, Up, Return: Port 2: Amiga (switch 2
#      appears, off); Down: switch 2; Return: on; Space: off; Space: on; Right, Return: Back;
#      Return; Run/Stop; Help closes the menu and saves (308, 309, 310, 312, 313, 314 change)
#   B  Help: Advanced Settings, cursor on Mouse; Return: Mouse (both switches on); Left,
#      Return: Port 1: C64 (switch 1 disappears, bit 310 stays set); Right, Return: Back;
#      Return; Run/Stop; Help closes the menu and saves (308, 309 change)
#   C  Help; Return: Mouse; Left, Down, Space: Port 1: Amiga (switch 1 appears, on); Down:
#      switch 1; Run/Stop; Help closes the menu and saves (308, 309 change)
set sd_int 1
reset
wait_uart 1500 MHz
wait_quiet 20000 300
dump a_boot"""
out.append(hdr)
mark("A: Help opens the menu")
help_open("a_menu")
mark("A: Right, Up, Up, Return: Advanced Settings")
key("Right"); key("Up"); key("Up", "a_cursor_adv"); key("Return", "a_adv")
mark("A: Right, Up, Up, Return: Mouse, both ports C64, no switch")
key("Right"); key("Up"); key("Up", "a_cursor_mouse"); key("Return", "a_mouse_none")
mark("A: none visible: Right, Return: Back")
key("Right", "a_cursor_back_none"); key("Return", "a_adv_back_none")
mark("A: Return: Mouse")
key("Return", "a_mouse_none2")
mark("A: none visible: Run/Stop")
key("Run/Stop", "a_adv_rs_none")
mark("A: Return: Mouse")
key("Return", "a_mouse_none3")
mark("A: Left, Down, Space: Port 1: Amiga")
key("Left"); key("Down", "a_cursor_m1amiga"); key("Space", "a_m1amiga")
mark("A: Down: switch 1")
key("Down", "a_cursor_sw1")
mark("A: Space: switch 1 on")
key("Space", "a_sw1_on_space")
mark("A: Return: switch 1 off")
key("Return", "a_sw1_off_return")
mark("A: Return: switch 1 on")
key("Return", "a_sw1_on_return")
mark("A: port 1 visible: Right, Return: Back")
key("Right", "a_cursor_back_s1"); key("Return", "a_adv_back_s1")
mark("A: Return: Mouse")
key("Return", "a_mouse_s1")
mark("A: port 1 visible: Run/Stop")
key("Run/Stop", "a_adv_rs_s1")
mark("A: Return: Mouse")
key("Return", "a_mouse_s1b")
mark("A: Right, Up, Return: Port 2: Amiga")
key("Right"); key("Up", "a_cursor_m2amiga"); key("Return", "a_m2amiga")
mark("A: Down: switch 2")
key("Down", "a_cursor_sw2")
mark("A: Return: switch 2 on")
key("Return", "a_sw2_on_return")
mark("A: Space: switch 2 off")
key("Space", "a_sw2_off_space")
mark("A: Space: switch 2 on")
key("Space", "a_sw2_on_space")
mark("A: both visible: Right, Return: Back")
key("Right", "a_cursor_back_both"); key("Return", "a_adv_back_both")
mark("A: Return: Mouse")
key("Return", "a_mouse_both")
mark("A: both visible: Run/Stop")
key("Run/Stop", "a_adv_rs_both")
mark("A: Help closes the menu")
help_close("a_closed")
mark("B: Help opens the menu again")
help_open("b_menu")
mark("B: Return: Mouse")
key("Return", "b_mouse")
mark("B: Left, Return: Port 1: C64")
key("Left", "b_cursor_m1c64"); key("Return", "b_m1c64")
mark("B: port 2 visible: Right, Return: Back")
key("Right", "b_cursor_back_s2"); key("Return", "b_adv_back_s2")
mark("B: Return: Mouse")
key("Return", "b_mouse_s2")
mark("B: port 2 visible: Run/Stop")
key("Run/Stop", "b_adv_rs_s2")
mark("B: Help closes the menu")
help_close("b_closed")
mark("C: Help opens the menu again")
help_open("c_menu")
mark("C: Return: Mouse")
key("Return", "c_mouse")
mark("C: Left, Down, Space: Port 1: Amiga")
key("Left"); key("Down", "c_cursor_m1amiga"); key("Space", "c_m1amiga")
mark("C: Down: switch 1")
key("Down", "c_cursor_sw1")
mark("C: both visible: Run/Stop")
key("Run/Stop", "c_adv_rs")
mark("C: Help closes the menu")
help_close("c_closed")
out.append("end")
open(os.path.join(HERE, "scenarios", "i2.stim"), "w").write("\n".join(out) + "\n")
print("scenarios/i2.stim: %d key presses" % sum(1 for l in out if l.startswith("press")))
