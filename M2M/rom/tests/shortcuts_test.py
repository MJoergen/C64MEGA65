#!/usr/bin/env python3
"""Runner for shortcuts_test.asm: keyboard shortcuts F9..F14 (C64MEGA65 #142).

1. Generates rewired copies of M2M/rom/shortcuts.asm, its variables and
   CORE/m2m-rom/shortcuts_c64.asm (hardware registers -> testbed RAM) plus
   the constants (menu.asm, sysdef.asm, mega65.vhd, config.vhd), and cuts the
   tail of HELP_MENU out of M2M/rom/options.asm (from _HLP_HEAP2_OK to its
   RET: the invisible session, the visible menu, the waiting time and the
   reconnect of keyboard and joysticks).
2. Assembles and runs the testbed headlessly in the QNICE emulator.
3. Compares its trace with the trace of an independent Python model of the
   shortcut logic.
4. Applies mutants to the generated code; each must change the trace.

done by sy2002 in 2026 and licensed under GPL v3
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
P = lambda *p: os.path.join(REPO, *p)

REWIRE = [(r"IO\$CYC_MID", "TB_CYC"), (r"M2M\$KEYBOARD", "TB_KEYB"),
          (r"M2M\$OSM_XY", "TB_OSM_XY"), (r"M2M\$OSM_DXDY", "TB_OSM_DXDY"),
          (r"M2M\$CSR(?![_A-Z0-9$])", "TB_CSR")]


def equs(path, pattern):
    out = {}
    for line in open(path, errors="replace"):
        m = re.match(pattern, line)
        if m:
            v = m.group(2)
            out[m.group(1)] = int(v, 16) if v.lower().startswith("0x") else int(v)
    return out


GEN = {"mod": "shortcuts_tbgen_mod.asm", "c64": "shortcuts_tbgen_c64.asm",
       "vars": "shortcuts_tbgen_vars.asm", "hlp": "shortcuts_tbgen_hlp.asm"}


def cut(path, start, through):
    """Lines from the one matching start up to (including) the first one
    matching through."""
    lines = open(path).read().split("\n")
    s = next((i for i, l in enumerate(lines) if re.match(start, l)), None)
    if s is None:
        sys.exit("cannot find %r in %s" % (start, path))
    e = next((i for i in range(s + 1, len(lines)) if re.match(through, lines[i])), None)
    if e is None:
        sys.exit("cannot find the end of %r in %s" % (start, path))
    return "\n".join(lines[s:e + 1]) + "\n"


def gen():
    sysdef = equs(P("M2M/rom/sysdef.asm"), r"^(M2M\$\S+)\s+\.EQU\s+(0x[0-9A-Fa-f]+|\d+)")
    menu = equs(P("M2M/rom/menu.asm"), r"^(OPTM_IR_GROUPS|OPTM_FP_GETKEY|OPTM_KEY_SELECT|OPTM_KEY_CLOSE)\s+\.EQU\s+(\d+)")
    menu.update(equs(P("M2M/rom/menu.asm"), r"^(OPTM_CLOSE)\s+\.EQU\s+(0x[0-9A-Fa-f]+|\d+)"))
    cmenu = equs(P("CORE/vhdl/mega65.vhd"), r"^constant (C_MENU_\w+)\s*:\s*natural\s*:=\s*(\d+);")
    cgrp = equs(P("CORE/vhdl/config.vhd"), r"^constant (OPTM_G_\w+)\s*:\s*integer\s*:=\s*(\d+);")
    c = {"C64_OSM_" + k[7:]: v for k, v in cmenu.items()}
    c.update({"C64_OPTM_G_" + k[7:]: v for k, v in cgrp.items()})
    dflt = {"F9": 1, "F10": 7, "F11": 2, "F12": 6, "F13": 9, "F14": 10}
    lines = ["; generated by shortcuts_test.py - do not edit"]
    for k, v in sorted(menu.items()):
        lines.append("%-27s .EQU %d" % (k, v))
    for k, v in sorted(c.items()):
        lines.append("%-27s .EQU %d" % (k, v))
    for k, v in dflt.items():
        lines.append("%-27s .EQU %d" % ("TB_DEF_" + k, c["C64_OSM_SC_" + k] + v))
    open(os.path.join(HERE, "shortcuts_tbgen_const.asm"), "w").write("\n".join(lines) + "\n")

    def rewire(s, drop=None):
        for a, b in REWIRE:
            s = re.sub(a, b, s)
        if drop:
            s = "\n".join(l for l in s.split("\n") if not re.match(drop, l))
        return s
    texts = {
        "mod": rewire(open(P("M2M/rom/shortcuts.asm")).read()),
        "c64": rewire(open(P("CORE/m2m-rom/shortcuts_c64.asm")).read()),
        "vars": rewire(open(P("M2M/rom/shortcuts_vars.asm")).read(), r"^OPTM_DIRECT\s"),
        "hlp": rewire(cut(P("M2M/rom/options.asm"), r"^_HLP_HEAP2_OK\s", r"^\s+RET\b")),
    }
    return sysdef, menu, c, dflt, texts


def write_gen(texts):
    for k, name in GEN.items():
        open(os.path.join(HERE, name), "w").write(texts[k])


class Model:
    """Independent model of shortcuts.asm + shortcuts_c64.asm (trace level)."""

    def __init__(self, sysdef, menu, c, dflt):
        self.k, self.m, self.c = sysdef, menu, c
        self.t = []
        self.cfm = [0] * 300
        for i in (c["C64_OSM_DRV8_IMG_MNT"], c["C64_OSM_DRV9_OFF"], c["C64_OSM_VOLUME_100"]):
            self.cfm[i] = 1
        self.pick = [c["C64_OSM_SC_F%d" % n] for n in range(9, 15)]
        for n, f in enumerate(range(9, 15)):
            self.cfm[self.pick[n] + dflt["F%d" % f]] = 1
        self.keyb, self.time, self.xy, self.dxdy = 0xFFFF, 0, 0, 0
        self.csr = sysdef["M2M$CSR_KBD_JOY"]       # OSM closed: keyboard is on
        self.toast_on, self.toast_t = 0, 0
        self.pend, self.save_t, self.force, self.block = 0, 0, 0, 0
        self.rep_key, self.rep_fkey, self.rep_t, self.rep_dly = 0, 0, 0, 0
        self.dirty = [0, 0]
        self.level, self.p_done, self.run_shift, self.nd_status = 0, 0, 0, 0
        self.groups = [0x1000, 0x0200, 0x8801, 0, 0x8802, 0, 0x8003, 0x8005, menu["OPTM_CLOSE"]]
        # keyread: a key of the user was read in this session (HM_KEYREAD);
        # cb_keys / nd_keys: the mount code behind a selected line / behind
        # next disk reads a key (file browser, error window)
        self.keyread, self.cb_keys, self.nd_keys = 0, 1, 0
        self.selected, self.start = 0, 0

    def out(self, *a):
        self.t.append(" ".join(a))

    def h(self, v):
        return "%04X" % (v & 0xFFFF)

    def set(self, i, v):
        self.cfm[i] = v
        self.out("SET", self.h(i), self.h(v))

    def toast(self, text):
        text = text[:41]
        dx = len(text) + 4
        x, y = (45 - dx) >> 1, 29
        self.out("CLR")
        self.out("FRAME", self.h(x), self.h(y), self.h(dx), self.h(3))
        self.out("TEXT", self.h(x + 2), self.h(y + 1), "|%s|" % text)
        self.xy, self.dxdy = (x << 8) | y, (dx << 8) | 3
        self.csr |= self.k["M2M$CSR_OSM"]
        self.toast_on, self.toast_t = 1, self.time

    def toast_off(self):
        if self.toast_on:
            self.toast_on = 0
            self.out("OFF")
            self.csr &= self.k["M2M$CSR_UN_OSM"]

    def save_later(self):
        self.pend, self.save_t = 1, self.time

    def help_head(self, direct):
        """HELP_MENU up to its tail: core paused, keyboard and joysticks off"""
        self.out("HM", self.h(self.k["M2M$KEY_HELP"]), self.h(direct))
        self.csr = (self.csr & self.k["M2M$CSR_UN_KBD_JOY"]) | self.k["M2M$CSR_PAUSE"]
        self.out("REM")

    def help_close(self):
        """overlay off, save the settings"""
        self.out("OFF")
        self.csr &= self.k["M2M$CSR_UN_OSM"]
        self.out("SAVE", self.h(self.force))

    def help_exit(self, wait):
        """the waiting time (only if wait) and the reconnect"""
        if wait:
            self.out("WAIT", self.h(self.csr))
        self.csr = (self.csr & self.k["M2M$CSR_UN_PAUSE"]) | self.k["M2M$CSR_KBD_JOY"]
        self.out("CSR", self.h(self.csr))

    def session(self, fn, arg):
        self.toast_off()
        self.keyread = 0
        self.help_head(1)
        r = fn(arg)
        self.help_close()
        self.help_exit(self.keyread)        # no key read: no waiting time
        return r

    def visible(self, select=False):
        """the user opens the menu with Help, selects the line under the
        cursor with Return if select is set, and closes the menu with Help"""
        sel = self.selected
        self.help_head(0)
        self.out("SHOW")
        self.out("ON")
        self.out("RUN", self.h(sel), self.h(self.level))
        if select:                          # the mount code behind the line
            self.out("K", self.h(self.m["OPTM_KEY_SELECT"]))
            self.out("CB")
            if self.cb_keys:
                self.keyread = 1
        self.out("K", self.h(self.m["OPTM_KEY_CLOSE"]))
        cur = sel + self.run_shift
        self.help_close()
        self.selected = self.start if self.groups[cur] == self.m["OPTM_CLOSE"] else cur
        self.help_exit(True)                # always, whatever keyread says

    def press_in(self, grp):
        idx = next((i for i, g in enumerate(self.groups) if g & 0xFF == grp), None)
        if idx is None:
            return 0
        self.out("RUN", self.h(idx), self.h(0))
        self.p_done = 0
        if idx + self.run_shift == idx:
            self.out("K", self.h(self.m["OPTM_KEY_SELECT"]))
            self.out("CB")
            if self.cb_keys:
                self.keyread = 1
            self.p_done = 1
        self.out("K", self.h(self.m["OPTM_KEY_CLOSE"]))
        return self.p_done

    def drive_ok(self, d):
        n = "Drive %d" % (8 + d)
        if self.cfm[self.c["C64_OSM_DRV%d_OFF" % (8 + d)]]:
            self.toast(n + " is off")
        elif self.cfm[self.c["C64_OSM_DRV%d_1581" % (8 + d)]]:
            self.toast(n + " is the internal 1581")
        elif self.dirty[d]:
            self.toast(n + " is still saving")
        else:
            return True
        return False

    def sc_key(self, f):
        base = self.pick[f]
        act = next((a for a in range(11) if self.cfm[base + a]), None)
        G = lambda g: self.c["C64_OPTM_G_" + g]
        if act in (2, 3):
            d = act - 2
            if self.drive_ok(d):
                self.session(self.press_in, G("MOUNT_%d" % (8 + d)))
        elif act in (4, 5):
            d = act - 4
            if self.drive_ok(d):
                msg = []

                def next_in(dd):
                    self.out("ND", self.h(dd))
                    if self.nd_keys:
                        self.keyread = 1
                    st = self.nd_status
                    if st == 0:
                        msg.append("Drive %d: GAME-SIDE-B.D64" % (8 + dd))
                    elif st in (1, 4):
                        self.press_in(G("MOUNT_%d" % (8 + dd)))
                    return st
                st = self.session(next_in, d)
                if st == 0:
                    self.toast(msg[0])
                else:
                    st = 5 if st > 5 else st
                    txt = {2: ": no other disk image", 3: " is still saving",
                           5: ": next disk failed"}.get(st)
                    if txt:
                        self.toast("Drive %d" % (8 + d) + txt)
        elif act == 6:
            self.session(self.press_in, G("LOAD_PRG"))
        elif act == 7:
            self.session(self.press_in, G("MOUNT_CRT"))
        elif act == 8:
            i = self.c["C64_OSM_FLIP_JOYS"]
            v = self.cfm[i] ^ 1
            self.set(i, v)
            self.save_later()
            self.toast("Joystick ports: " + ("flipped" if v else "normal"))
        elif act in (9, 10):
            vb = self.c["C64_OSM_VOLUME_100"]
            cur = next((l for l in range(21) if self.cfm[vb + l]), 0)
            new = min(20, max(0, cur + (1 if act == 9 else -1)))
            if new != cur:
                self.set(vb + new, 1)
                self.set(vb + cur, 0)
                self.save_later()
            self.toast("Volume: %d%%" % (100 - 5 * new))
            return 1
        return 0

    def tb_sckey(self, f):
        self.out("KEY", self.h(f))
        self.out("C", self.h(self.sc_key(f)))

    def fkey(self, key):
        b = {self.k["M2M$KEY_F9"]: 0, self.k["M2M$KEY_F11"]: 2, self.k["M2M$KEY_F13"]: 4}.get(key)
        if b is None:
            return 0xFFFF
        return b + (0 if self.keyb & self.k["M2M$KEY_SHIFT"] else 1)

    def toast_tick(self):
        if self.toast_on and ((self.time - self.toast_t) & 0xFFFF) >= 763:
            self.toast_off()

    def save_tick(self):
        if self.pend and ((self.time - self.save_t) & 0xFFFF) >= 2289:
            self.force = 1
            self.out("SAVE", self.h(1))
            if self.block:
                self.force = 2
            if self.force == 2:
                self.save_t = self.time
            else:
                self.pend = 0
            self.force = 0

    def main(self, key):
        self.out("MAIN", self.h(key), self.h(self.time))
        if key == self.k["M2M$KEY_HELP"]:
            self.toast_off()
            self.rep_key = 0
        self.toast_tick()
        self.save_tick()
        if self.rep_key:
            if self.keyb & self.rep_key:
                self.rep_key = 0
            elif ((self.time - self.rep_t) & 0xFFFF) >= self.rep_dly:
                self.rep_t, self.rep_dly = self.time, 115
                if not self.sc_key(self.rep_fkey):
                    self.rep_key = 0
        f = self.fkey(key)
        if f != 0xFFFF:
            self.rep_key = 0
            if self.sc_key(f):
                self.rep_key, self.rep_fkey, self.rep_dly, self.rep_t = key, f, 381, self.time

    def pickset(self, fkey_base, item):
        for a in range(11):
            self.cfm[fkey_base + a] = 0
        self.cfm[fkey_base + item] = 1


def expected(sysdef, menu, c, dflt):
    M = Model(sysdef, menu, c, dflt)
    K = sysdef
    M.out("== T1 function keys")
    for key in (K["M2M$KEY_F9"], K["M2M$KEY_F11"], K["M2M$KEY_F13"], K["M2M$KEY_F1"],
                K["M2M$KEY_HELP"], K["M2M$KEY_SHIFT"], 0):
        for kb in (0xFFFF, 0xDFFF):
            M.keyb = kb
            M.out("FK", M.h(key), M.h(kb), M.h(M.fkey(key)))
    M.keyb = 0xFFFF
    M.out("== T2 volume")
    for _ in range(21):
        M.tb_sckey(4)
    for _ in range(21):
        M.tb_sckey(5)
    vb = c["C64_OSM_VOLUME_100"]
    M.out("VB", *[M.h(l) for l in range(21) if M.cfm[vb + l]])
    M.out("== T3 flip")
    M.pickset(c["C64_OSM_SC_F12"], 8)
    M.pend = 0
    M.tb_sckey(3)
    M.out("VAL", M.h(M.pend))
    M.tb_sckey(3)
    M.out("== T4 mount")
    def drvmode(d, item):
        b = c["C64_OSM_DRV%d_IMG_MNT" % d]
        for a in range(4):
            M.cfm[b + a] = 0
        M.cfm[b + item] = 1
    drvmode(8, 2); M.tb_sckey(2)
    drvmode(8, 3); M.tb_sckey(2)
    drvmode(8, 0); M.dirty[0] = 1; M.tb_sckey(2)
    M.dirty[0] = 0; M.level = 7; M.tb_sckey(2)
    M.out("VAL", M.h(7)); M.out("VAL", M.h(1))
    M.pickset(c["C64_OSM_SC_F12"], 3); M.tb_sckey(3)
    M.out("== T5 hidden")
    M.run_shift = 1; M.tb_sckey(2); M.out("VAL", M.h(M.p_done)); M.run_shift = 0
    M.out("VAL", M.h(M.session(M.press_in, c["C64_OPTM_G_HDMI_ZOOM"])))
    M.out("== T6 next disk")
    M.pickset(c["C64_OSM_SC_F11"], 4)
    for st in (0, 2, 3, 1, 4, 5, 7):
        M.nd_status = st
        M.tb_sckey(2)
    M.out("== T7 prg crt")
    M.pickset(c["C64_OSM_SC_F12"], 6); M.tb_sckey(3); M.tb_sckey(1); M.tb_sckey(0)
    M.pickset(c["C64_OSM_SC_F9"], 0); M.tb_sckey(0)
    M.out("== T8 message")
    long = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwx"
    for s in (long, "Hi"):
        M.toast(s)
        M.out("OSM", M.h(M.xy), M.h(M.dxdy), M.h(M.csr))
    M.out("== T9 message timeout")
    def tt(t):
        M.time = t; M.toast_tick(); M.out("TT", M.h(t), M.h(M.toast_on))
    M.time = 1000; M.toast("Hi"); tt(1762); tt(1763)
    M.time = 65000; M.toast("Hi"); tt(226); tt(227)
    M.out("== T10 deferred save")
    def ts(t):
        M.time = t; M.save_tick()
        M.out("ST", M.h(t), M.h(M.pend), M.h(M.force), M.h(M.save_t))
    M.time = 5000; M.save_later(); ts(7288); ts(7289)
    M.block = 1; M.time = 100; M.save_later(); ts(2389)
    M.block = 0; ts(4677); ts(4678)
    M.out("== T11 key repeat")
    for l in range(21):
        M.cfm[vb + l] = 0
    M.cfm[vb] = 1
    M.time = 10000; M.keyb = 0xEFFF; M.main(K["M2M$KEY_F13"])
    for t in (10380, 10381, 10495, 10496):
        M.time = t; M.main(0)
    M.keyb = 0xFFFF; M.time = 20000; M.main(0)
    M.out("VAL", M.h(M.rep_key))
    M.out("== T12 shift layer and help")
    M.time = 30000; M.keyb = 0xCFFF; M.main(K["M2M$KEY_F13"])
    M.keyb = 0xFFFF; M.main(K["M2M$KEY_HELP"])
    M.out("VAL", M.h(M.toast_on))
    M.out("== T13 sessions with and without key")
    M.pickset(c["C64_OSM_SC_F11"], 4)
    M.nd_status = 0
    M.nd_keys = 1; M.tb_sckey(2)                    # next disk, error window
    M.nd_keys = 0; M.tb_sckey(2)                    # next disk, directly
    M.pickset(c["C64_OSM_SC_F12"], 2); M.tb_sckey(3)    # mount: file browser
    M.cb_keys = 0; M.tb_sckey(3)                    # mount: no key read
    M.pickset(c["C64_OSM_SC_F12"], 6); M.tb_sckey(3)    # PRG: no key read
    M.pickset(c["C64_OSM_SC_F12"], 7); M.tb_sckey(3)    # CRT: no key read
    M.cb_keys = 1
    M.out("== T14 visible menu")
    M.start = 1
    for sel, keyread in ((2, 0), (2, 1), (8, 0), (8, 1)):
        M.selected, M.keyread = sel, keyread
        M.visible()
        M.out("VAL", M.h(M.selected))
    M.out("== T15 key flag after the visible menu")
    M.keyread, M.selected = 0, 2
    M.visible(select=True)                          # mounts: the flag is set
    M.out("VAL", M.h(M.keyread))
    M.pickset(c["C64_OSM_SC_F11"], 4)
    M.nd_status = 0; M.tb_sckey(2)                  # next disk, no key read
    M.pickset(c["C64_OSM_SC_F12"], 2); M.tb_sckey(3)    # mount: file browser
    M.visible()                                     # Help, Help
    M.out("VAL", M.h(M.keyread))
    M.tb_sckey(2)                                   # next disk, no key read
    M.out("DONE")
    return "\n".join(M.t) + "\n"


def mutant(part, pattern, repl):
    """A mutant replaces the only match of pattern in one generated text."""
    def mutate(texts):
        s, n = re.subn(pattern, repl, texts[part], flags=re.M)
        return dict(texts, **{part: s}) if n == 1 else None
    return mutate


