#!/usr/bin/env python3
"""
Regression test for the 512-bit menu state register of QNICE (M2M$CFM_ADDR /
M2M$CFM_DATA in sysdef.asm, control_m_o in M2M/vhdl/QNICE/qnice.vhd): one bit
per menu item, so a menu can have up to 512 items in 32 banks of 16 bits.

The QNICE emulator has no M2M registers, so this test runs on simulated
hardware instead: it builds cfm_test.asm as a self-contained RELEASE-style ROM
(QNICE Monitor at 0x0000, exactly like m2m-rom.asm), simulates the real QNICE
CPU inside the real qnice.vhd with ghdl (cfm_tb.vhd) and checks that

    * the bank selector stores 5 bits and the 32 banks are distinct,
    * M2M$SET_SETTING / M2M$GET_SETTING (tools.asm) reach every item from 0
      to 511, and
    * ROSM_REM_OLD / ROSM_CHANGES (options.asm) see changes in all 32 banks,
      including item 511 and the first item above the old 256-bit limit.

The routines under test are copied verbatim from the Shell sources into the
generated cfm_test_extract.asm on every run, so the test always exercises the
current code. Run it from anywhere:

    python3 cfm_test.py

Requires ghdl and the QNICE toolchain built for the host platform, see
AGENTS.md section 7. Skips (exit code 0) when ghdl is not installed.
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
ROM_SRC = os.path.join(REPO, "M2M", "rom")
QNICE = os.path.join(REPO, "M2M", "QNICE")
ASM = os.path.join(QNICE, "assembler", "asm")

# (source file, first line regex, regex of the first line NOT to copy)
EXTRACTS = [
    ("tools.asm", r"M2M\$GET_SETTING\s", r"; M2M\$FORCE_MENU"),
    ("options.asm", r"ROSM_REM_OLD\s", r"; For preventing data corruption"),
    ("options.asm", r"ROSM_CHANGES\s", r"; Save the current state of"),
]

# the QNICE SoC as listed in the CORE-R?.xpr projects, in analysis order
# (without sd_spi.vhd, which only the replaced SD card controller needs)
QNICE_VHDL = [
    "M2M/vhdl/QNICE/qnice_globals.vhd",
    "M2M/QNICE/vhdl/tools.vhd",
    "M2M/QNICE/vhdl/cpu_constants.vhd",
    "M2M/QNICE/vhdl/alu_shifter.vhd",
    "M2M/QNICE/vhdl/alu.vhd",
    "M2M/QNICE/vhdl/register_file.vhd",
    "M2M/QNICE/vhdl/qnice_cpu.vhd",
    "M2M/QNICE/vhdl/block_rom.vhd",
    "M2M/QNICE/vhdl/block_ram.vhd",
    "M2M/QNICE/vhdl/byte_bram.vhd",
    "M2M/QNICE/vhdl/fifo.vhd",
    "M2M/QNICE/vhdl/basic_uart.vhd",
    "M2M/QNICE/vhdl/bus_uart.vhd",
    "M2M/QNICE/vhdl/EAE.vhd",
    "M2M/QNICE/vhdl/sdcard.vhd",            # idle stub, see SDCARD_STUB
    "M2M/QNICE/vhdl/cycle_counter.vhd",
    "M2M/vhdl/QNICE/qnice_mmio.vhd",
    "M2M/vhdl/QNICE/sdmux.vhd",
    "M2M/vhdl/QNICE/qnice.vhd",
]

# two QNICE-FPGA files use syntax that ghdl rejects in VHDL-2008 mode (Vivado
# accepts it); the test analyzes patched copies, the sources stay untouched
GHDL_PATCHES = {
    "block_rom.vhd": [(r"file\s+rom_file\s*:\s*text\s+is\s+in\s+rom_file_name;",
                       "file rom_file : text open read_mode is rom_file_name;")],
    "cycle_counter.vhd": [(r"(\n(\s*)when \"11\" => [^\n]*\n)",
                           "\\1\\2when others => null;\n")],
}


# The SD card controller is not involved in the menu state and its SPI state
# machine trips a simulation-only range check while it idles without a card,
# so the test replaces it by an idle stub that keeps the real entity
# declaration of sdcard.vhd (a changed port list still fails to elaborate).
SDCARD_STUB = """
architecture stub of sdcard is
begin
   data_out <= (others => '0');
   sd_reset <= '1';
   sd_clk   <= '0';
   sd_mosi  <= '1';
end architecture stub;
"""


def sdcard_stub(src):
    text = open(src).read()
    s = re.search(r"^library.*?^end\s+(entity\s+)?sdcard\s*;", text,
                  re.S | re.M | re.I)
    if not s:
        sys.exit("FAIL: entity sdcard not found in " + src)
    return s.group(0) + "\n" + SDCARD_STUB


def extract():
    out = ["; AUTOGENERATED by cfm_test.py - DO NOT EDIT", ""]
    for name, first, stop in EXTRACTS:
        lines = open(os.path.join(ROM_SRC, name)).read().split("\n")
        s = next(i for i, l in enumerate(lines) if re.match(first, l))
        e = next(i for i in range(s + 1, len(lines)) if re.match(stop, lines[i]))
        out.append("; ---- %s: %s" % (name, lines[s].split()[0]))
        out += lines[s:e]
    with open(os.path.join(HERE, "cfm_test_extract.asm"), "w") as f:
        f.write("\n".join(out) + "\n")


def assemble():
    res = subprocess.run([ASM, "cfm_test.asm"], cwd=HERE, capture_output=True,
                         text=True, timeout=120)
    rom = os.path.join(HERE, "cfm_test.rom")
    if res.returncode != 0 or not os.path.exists(rom):
        print(res.stdout[-3000:])
        print(res.stderr[-3000:], file=sys.stderr)
        sys.exit("FAIL: could not assemble cfm_test.asm")
    return rom


def simulate(ghdl, rom):
    work = tempfile.mkdtemp(prefix="ghdl_cfm_")
    opts = ["--std=08", "-frelaxed", "-fsynopsys", "--workdir=" + work]
    try:
        files = []
        for rel in QNICE_VHDL:
            src = os.path.join(REPO, rel)
            name = os.path.basename(rel)
            if name == "sdcard.vhd":
                src = os.path.join(work, name)
                with open(src, "w") as f:
                    f.write(sdcard_stub(os.path.join(REPO, rel)))
            elif name in GHDL_PATCHES:
                text = open(src).read()
                for rx, rep in GHDL_PATCHES[name]:
                    text, n = re.subn(rx, rep, text)
                    if n == 0:
                        sys.exit("FAIL: ghdl patch for %s does not apply" % name)
                src = os.path.join(work, name)
                with open(src, "w") as f:
                    f.write(text)
            files.append(src)
        files.append(os.path.join(HERE, "cfm_tb.vhd"))
        out = ""
        for step in ([[ghdl, "-a"] + opts + files,
                      [ghdl, "-e"] + opts + ["cfm_tb"],
                      [ghdl, "-r"] + opts + ["cfm_tb", "-gG_ROM=" + rom,
                                             "--assert-level=error",
                                             "--ieee-asserts=disable"]]):
            res = subprocess.run(step, cwd=work, capture_output=True,
                                 text=True, timeout=600)
            out = res.stdout + res.stderr
            if res.returncode != 0:
                break
        return out
    finally:
        shutil.rmtree(work, ignore_errors=True)


def main():
    ghdl = shutil.which("ghdl") or (
        "/usr/local/bin/ghdl" if os.path.exists("/usr/local/bin/ghdl") else None)
    if not ghdl:
        print("CFM TEST: SKIP (ghdl not found)")
        return 0
    extract()
    rom = assemble()
    out = simulate(ghdl, rom)
    for line in out.splitlines():
        if "CFM_TB" in line:
            print(line[line.index("CFM_TB"):])
    if "CFM_TB OK" in out and "CFM_TB FAIL" not in out:
        print("CFM TEST OK")
        return 0
    if "CFM_TB" not in out:
        print(out[-3000:])
    print("CFM TEST FAILED")
    return 1


if __name__ == "__main__":
    sys.exit(main())
