;
; Equivalence harness: the no-breaking-changes regression gate for the
; M2M V2.1.0 bracket parser (see doc/path-to-OSM-submenus.md section 4.3
; in the C64MEGA65 repository).
;
; Contains a verbatim copy of the pre-V2.1.0 three-pass toggle parser
; (_OLDSTR, copied from menu.asm as of M2M V2.0.0 with renamed labels) and
; runs it side by side with the new _OPTM_STRUCT over legacy-shaped fixtures
; (including the complete pre-V6 C64 menu and 150 seeded-random legacy
; configurations) at every menu level. The structure arrays and the visible
; line counts must match word for word.
;
; Fixtures are generated by menu_test.py; run the whole suite with:
;     python3 menu_test.py run
;
