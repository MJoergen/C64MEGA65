                MOVE    NT_S_BEGIN, R8
                SYSCALL(puts, 1)
                SYSCALL(crlf, 1)

                ; copy the default selected-state array into RAM (the menu
                ; modifies it) and zero-initialize the lines array
                MOVE    NAV_STDSEL_DEF, R0
                MOVE    NT_STDSEL, R1
                MOVE    NT_LINES, R2
                MOVE    NAV_N, R3
_NT_CPY         MOVE    @R0++, @R1++
                MOVE    0, @R2++
                SUB     1, R3
                RBRA    _NT_CPY, !Z

                MOVE    NT_SCEN, R8             ; scenario counter := 0
                MOVE    0, @R8
                MOVE    NT_SCR, R8              ; screen trace off
                MOVE    0, @R8
                MOVE    NT_SCRIPT_POS, R8       ; script position := 0
                MOVE    NAV_SCRIPT, @R8
                MOVE    NT_SCRIPT_END, R8
                MOVE    NAV_SCRIPT, R9
                ADD     NAV_SCRIPT_CNT, R9
                MOVE    R9, @R8

                MOVE    NT_REC, R8              ; initialize the menu
                MOVE    0, R9                   ; x
                MOVE    0, R10                  ; y
                MOVE    30, R11                 ; dx
                MOVE    30, R12                 ; dy
                RSUB    OPTM_INIT, 1

                MOVE    NT_CURSOR, R8           ; cursor := start item
                MOVE    NAV_START, @R8

                ; run the menu; re-run it after each close while script
                ; entries are left (tests menu level persistence). Like
                ; HELP_MENU in production, draw the menu via OPTM_SHOW
                ; before running it: this exercises the %s machinery at
                ; the current (possibly persisted) menu level
_NT_RUN         RSUB    OPTM_SHOW, 1
                MOVE    NT_CURSOR, R8
                MOVE    @R8, R8
                RSUB    OPTM_RUN, 1
                MOVE    NT_CURSOR, R9           ; remember returned cursor
                MOVE    R8, @R9

                MOVE    NT_S_R, R8              ; print "R C=<cursor>"
                SYSCALL(puts, 1)
                MOVE    NT_CURSOR, R8
                MOVE    @R8, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)

                MOVE    NT_SCRIPT_POS, R8       ; script exhausted?
                MOVE    @R8, R8
                MOVE    NT_SCRIPT_END, R9
                CMP     R8, @R9
                RBRA    _NT_RUN, !Z             ; no: run the menu again

                ; ------------------------------------------------------------
                ; Advance to the next scenario:
                ;  2 = synthetic menu covering the enter-scan stop positions
                ;      the V6 menu cannot provide (a region whose first content
                ;      is a nested child opener and an empty region)
                ;  3 = dependency menu covering the live OPTM_RUN dependency
                ;      paths: the enter-scan dependency skip and the real-time
                ;      redraw on a mother toggle
                ;  4 = the V6 menu of scenario 1 with the dependency feature
                ;      on and the screen trace on: the dependent switches of
                ;      the Mouse submenu
                ; (see nav2_script() / nav3_script() / nav4_script() in
                ; menu_test.py)
                ; ------------------------------------------------------------

                MOVE    NT_SCEN, R8
                ADD     1, @R8
                MOVE    @R8, R0                 ; R0: scenario number
                CMP     1, R0
                RBRA    _NT_SCEN2, Z
                CMP     2, R0
                RBRA    _NT_SCEN3, Z
                CMP     3, R0
                RBRA    _NT_SCEN4, Z
                RBRA    _NT_DONE, 1             ; all scenarios done

_NT_SCEN2       MOVE    NT_S_N2, R8            ; print the scenario marker
                SYSCALL(puts, 1)
                SYSCALL(crlf, 1)

                MOVE    NAV2_STDSEL_DEF, R0     ; selected-state defaults
                MOVE    NT_STDSEL, R1
                MOVE    NAV2_N, R3
_NT_CPY2        MOVE    @R0++, @R1++
                SUB     1, R3
                RBRA    _NT_CPY2, !Z

                MOVE    NT_REC, R8              ; repoint the init record
                ADD     OPTM_IR_SIZE, R8
                MOVE    NAV2_N, @R8
                MOVE    NT_REC, R8
                ADD     OPTM_IR_ITEMS, R8
                MOVE    NAV2_ITEMS, @R8
                MOVE    NT_REC, R8
                ADD     OPTM_IR_GROUPS, R8
                MOVE    NAV2_GROUPS, @R8

                MOVE    NT_SCRIPT_POS, R8       ; switch to script 2
                MOVE    NAV2_SCRIPT, @R8
                MOVE    NT_SCRIPT_END, R8
                MOVE    NAV2_SCRIPT, R9
                ADD     NAV2_SCRIPT_CNT, R9
                MOVE    R9, @R8

                MOVE    NT_REC, R8              ; re-initialize like a boot
                MOVE    0, R9
                MOVE    0, R10
                MOVE    30, R11
                MOVE    30, R12
                RSUB    OPTM_INIT, 1

                MOVE    NT_CURSOR, R8           ; cursor := start item
                MOVE    NAV2_START, @R8
                RBRA    _NT_RUN, 1

_NT_SCEN3       MOVE    NT_S_N3, R8            ; print the scenario marker
                SYSCALL(puts, 1)
                SYSCALL(crlf, 1)

                MOVE    NAV3_STDSEL_DEF, R0     ; selected-state defaults
                MOVE    NT_STDSEL, R1
                MOVE    NAV3_N, R3
_NT_CPY3        MOVE    @R0++, @R1++
                SUB     1, R3
                RBRA    _NT_CPY3, !Z

                MOVE    NT_REC, R8              ; repoint the init record and
                ADD     OPTM_IR_SIZE, R8        ; turn the dependency feature ON
                MOVE    NAV3_N, @R8             ; by pointing OPTM_IR_DEPS at the
                MOVE    NT_REC, R8              ; resolved array
                ADD     OPTM_IR_ITEMS, R8
                MOVE    NAV3_ITEMS, @R8
                MOVE    NT_REC, R8
                ADD     OPTM_IR_GROUPS, R8
                MOVE    NAV3_GROUPS, @R8
                MOVE    NT_REC, R8
                ADD     OPTM_IR_DEPS, R8
                MOVE    NAV3_DEPS, @R8

                MOVE    NT_SCRIPT_POS, R8       ; switch to script 3
                MOVE    NAV3_SCRIPT, @R8
                MOVE    NT_SCRIPT_END, R8
                MOVE    NAV3_SCRIPT, R9
                ADD     NAV3_SCRIPT_CNT, R9
                MOVE    R9, @R8

                MOVE    NT_REC, R8              ; re-initialize like a boot
                MOVE    0, R9
                MOVE    0, R10
                MOVE    30, R11
                MOVE    30, R12
                RSUB    OPTM_INIT, 1

                MOVE    NT_CURSOR, R8           ; cursor := start item
                MOVE    NAV3_START, @R8
                RBRA    _NT_RUN, 1

_NT_SCEN4       MOVE    NT_S_N4, R8            ; print the scenario marker
                SYSCALL(puts, 1)
                SYSCALL(crlf, 1)

                MOVE    NAV_STDSEL_DEF, R0      ; selected-state defaults
                MOVE    NT_STDSEL, R1           ; and the separator flags
                MOVE    NAV4_LINES, R2
                MOVE    NT_LINES, R4
                MOVE    NAV_N, R3
_NT_CPY4        MOVE    @R0++, @R1++
                MOVE    @R2++, @R4++
                SUB     1, R3
                RBRA    _NT_CPY4, !Z

                MOVE    NT_REC, R8              ; repoint the init record to
                ADD     OPTM_IR_SIZE, R8        ; the V6 menu and turn the
                MOVE    NAV_N, @R8              ; dependency feature ON
                MOVE    NT_REC, R8
                ADD     OPTM_IR_ITEMS, R8
                MOVE    NAV_ITEMS, @R8
                MOVE    NT_REC, R8
                ADD     OPTM_IR_GROUPS, R8
                MOVE    NAV_GROUPS, @R8
                MOVE    NT_REC, R8
                ADD     OPTM_IR_DEPS, R8
                MOVE    NAV4_DEPS, @R8

                MOVE    NT_SCRIPT_POS, R8       ; switch to script 4
                MOVE    NAV4_SCRIPT, @R8
                MOVE    NT_SCRIPT_END, R8
                MOVE    NAV4_SCRIPT, R9
                ADD     NAV4_SCRIPT_CNT, R9
                MOVE    R9, @R8

                MOVE    NT_SCR, R8              ; screen trace on
                MOVE    1, @R8

                MOVE    NT_REC, R8              ; re-initialize like a boot,
                MOVE    NAV4_X, R9              ; with the menu away from the
                MOVE    0, R10                  ; left edge like in the Shell
                MOVE    30, R11
                MOVE    30, R12
                RSUB    OPTM_INIT, 1

                MOVE    NT_CURSOR, R8           ; cursor := start item
                MOVE    NAV_START, @R8
                RBRA    _NT_RUN, 1

_NT_DONE        MOVE    NT_S_DONE, R8
                SYSCALL(puts, 1)
                SYSCALL(crlf, 1)
                SYSCALL(exit, 1)

; ----------------------------------------------------------------------------
; Initialization record: stubbed screen functions, scripted key feed
; ----------------------------------------------------------------------------

NT_REC          .DW     NT_CLEAR, NT_FRAME, NT_PRINT, NT_PRINTXY
                .DW     NT_LINE, NT_SELECT, NT_GETKEY
                .DW     NT_CB_SEL, NT_CB_SHOW, NT_FATAL
                .DW     0x0072, 0, 0x0073, 0    ; sel. chars (inline strings):
                                                ; r = radio, s = single-select
                .DW     NAV_N, NAV_ITEMS, NAV_GROUPS, NT_STDSEL, NT_LINES, 0
                                                ; last word = OPTM_IR_DEPS: 0 =
                                                ; dependency feature off here

                ; The screen functions: with the screen trace off they do
                ; nothing; all of them preserve all registers

                ; OPTM_FP_CLEAR: with the screen trace on, print C
NT_CLEAR        INCRB
                MOVE    NT_SCR, R0
                CMP     0, @R0
                RBRA    _NT_CL_RET, Z           ; screen trace off
                MOVE    R8, R6                  ; preserve R8
                MOVE    NT_S_CL, R8             ; "C"
                SYSCALL(puts, 1)
                SYSCALL(crlf, 1)
                MOVE    R6, R8                  ; restore R8
_NT_CL_RET      DECRB
                RET

                ; OPTM_FP_FRAME: R8 = x, R9 = y, R10 = dx, R11 = dy. With the
                ; screen trace on, print all four
NT_FRAME        INCRB
                MOVE    NT_SCR, R0
                CMP     0, @R0
                RBRA    _NT_FR_RET, Z           ; screen trace off
                MOVE    R8, R6                  ; preserve R8
                MOVE    R8, R0                  ; R0 to R3: x, y, dx, dy
                MOVE    R9, R1
                MOVE    R10, R2
                MOVE    R11, R3
                MOVE    NT_S_FR, R8             ; "FR X="
                SYSCALL(puts, 1)
                MOVE    R0, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_XY, R8             ; " Y="
                SYSCALL(puts, 1)
                MOVE    R1, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_FW, R8             ; " W="
                SYSCALL(puts, 1)
                MOVE    R2, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_FH, R8             ; " H="
                SYSCALL(puts, 1)
                MOVE    R3, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)
                MOVE    R6, R8                  ; restore R8
_NT_FR_RET      DECRB
                RET

                ; OPTM_FP_LINE: R8 = row of the separator. With the screen
                ; trace on, print the row
NT_LINE         INCRB
                MOVE    NT_SCR, R0
                CMP     0, @R0
                RBRA    _NT_LN_RET, Z           ; screen trace off
                MOVE    R8, R6                  ; preserve R8
                MOVE    NT_S_LN, R8             ; "L Y="
                SYSCALL(puts, 1)
                MOVE    R6, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)
                MOVE    R6, R8                  ; restore R8
_NT_LN_RET      DECRB
                RET

                ; OPTM_FP_SELECT: R8 = position in the current view, R9 =
                ; mode (OPTM_SEL_STD, _SEL, _TLL, _TLLSEL). With the screen
                ; trace on, print both
NT_SELECT       INCRB
                MOVE    NT_SCR, R0
                CMP     0, @R0
                RBRA    _NT_SL_RET, Z           ; screen trace off
                MOVE    R8, R6                  ; preserve R8
                MOVE    R9, R1                  ; R1: mode
                MOVE    NT_S_BP, R8             ; "B P="
                SYSCALL(puts, 1)
                MOVE    R6, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_BM, R8             ; " M="
                SYSCALL(puts, 1)
                MOVE    R1, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)
                MOVE    R6, R8                  ; restore R8
_NT_SL_RET      DECRB
                RET

                ; OPTM_FP_PRINT: R8 = string, R9 = mask array (size, then
                ; one word per line, bit 15 = drawn). With the screen trace
                ; on, print the flat index of every drawn line
NT_PRINT        INCRB
                MOVE    NT_SCR, R0
                CMP     0, @R0
                RBRA    _NT_PR_RET, Z           ; screen trace off
                MOVE    R8, R6                  ; preserve R8
                MOVE    R9, R0                  ; R0: mask array
                MOVE    @R0++, R1               ; R1: number of lines
                XOR     R2, R2                  ; R2: flat index
                MOVE    NT_S_D, R8              ; "D"
                SYSCALL(puts, 1)
_NT_PR_1        MOVE    @R0++, R3
                AND     0x8000, R3              ; drawn?
                RBRA    _NT_PR_2, Z             ; no
                MOVE    NT_S_SP, R8
                SYSCALL(puts, 1)
                MOVE    R2, R8
                SYSCALL(puthex, 1)
_NT_PR_2        ADD     1, R2
                SUB     1, R1
                RBRA    _NT_PR_1, !Z
                SYSCALL(crlf, 1)
                MOVE    R6, R8                  ; restore R8
_NT_PR_RET      DECRB
                RET

                ; OPTM_FP_PRINTXY: R8 = string, R9 = x, R10 = y. With the
                ; screen trace on, print the column, the row and the string
NT_PRINTXY      INCRB
                MOVE    NT_SCR, R0
                CMP     0, @R0
                RBRA    _NT_PX_RET, Z           ; screen trace off
                MOVE    R8, R6                  ; preserve R8
                MOVE    NT_S_XX, R8             ; "X X="
                SYSCALL(puts, 1)
                MOVE    R9, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_XY, R8             ; " Y="
                SYSCALL(puts, 1)
                MOVE    R10, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_LB, R8             ; " ["
                SYSCALL(puts, 1)
                MOVE    R6, R8                  ; the string
                SYSCALL(puts, 1)
                MOVE    NT_S_RB, R8             ; "]"
                SYSCALL(puts, 1)
                SYSCALL(crlf, 1)
                MOVE    R6, R8                  ; restore R8
_NT_PX_RET      DECRB
                RET

                ; scripted OPTM_FP_GETKEY: print the state trace, optionally
                ; simulate a background redraw, return the next key in R8
NT_GETKEY       INCRB

                MOVE    NT_S_K, R8              ; "K L="
                SYSCALL(puts, 1)
                MOVE    OPTM_MENULEVEL, R8
                MOVE    @R8, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_C, R8              ; " C="
                SYSCALL(puts, 1)
                MOVE    OPTM_CUR_SEL, R8
                MOVE    @R8, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_P, R8              ; " P="
                SYSCALL(puts, 1)
                MOVE    OPTM_LVL_PARENT, R8
                MOVE    @R8, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_O, R8              ; " O="
                SYSCALL(puts, 1)
                MOVE    OPTM_LVL_OPENER, R8
                MOVE    @R8, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)

                MOVE    NT_SCRIPT_POS, R0       ; script exhausted?
                MOVE    @R0, R1
                MOVE    NT_SCRIPT_END, R2
                MOVE    @R2, R2
                CMP     R1, R2
                RBRA    _NT_GK_1, !Z
                MOVE    NT_S_X, R8              ; yes: should not happen:
                SYSCALL(puts, 1)                ; print "X" and force close
                SYSCALL(crlf, 1)
                MOVE    OPTM_KEY_CLOSE, R8
                RBRA    _NT_GK_RET, 1

_NT_GK_1        MOVE    @R1, R2                 ; R2: next script word
                ADD     1, @R0                  ; advance the script

                MOVE    R2, R3
                AND     0x8000, R3              ; redraw marker?
                RBRA    _NT_GK_2, Z             ; no

                RSUB    OPTM_SHOW, 1            ; simulate the background
                MOVE    OPTM_CUR_SEL, R8        ; redraw exactly like the
                MOVE    @R8, R8                 ; vdrive status change in
                MOVE    OPTM_SEL_SEL, R9        ; options.asm does it
                RSUB    OPTM_SELECT, 1

_NT_GK_2        MOVE    R2, R8                  ; return the key
                AND     0x7FFF, R8

_NT_GK_RET      DECRB
                RET

                ; %s callback: OPTM_SHOW calls this for every line that
                ; contains a %s and that is visible at the current menu
                ; level; print the flat line index and return the string
                ; unchanged (no replacement). The W trace lines verify that
                ; the %s scanner of OPTM_SHOW keeps its line counter in
                ; sync, also across labels whose last character is a
                ; percent sign (" 100%" and friends)
NT_CB_SHOW      INCRB
                MOVE    R8, R0                  ; preserve the string ptr
                MOVE    R9, R1                  ; preserve the line index

                MOVE    NT_S_W, R8              ; "W I="
                SYSCALL(puts, 1)
                MOVE    R1, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)

                MOVE    R0, R8                  ; return string unchanged
                MOVE    R1, R9
                DECRB
                RET

                ; selection callback: print the group word, the item index
                ; within the group and the key that selected it
NT_CB_SEL       INCRB
                MOVE    R8, R0
                MOVE    R9, R1
                MOVE    R10, R2

                MOVE    NT_S_S, R8              ; "S G="
                SYSCALL(puts, 1)
                MOVE    R0, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_I, R8              ; " I="
                SYSCALL(puts, 1)
                MOVE    R1, R8
                SYSCALL(puthex, 1)
                MOVE    NT_S_KY, R8             ; " K="
                SYSCALL(puts, 1)
                MOVE    R2, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)

                MOVE    NT_SCR, R3              ; screen trace on: print the
                CMP     0, @R3                  ; flat index of every item
                RBRA    _NT_SEL_RET, Z          ; that is selected now
                MOVE    NT_S_M, R8              ; "M"
                SYSCALL(puts, 1)
                MOVE    NT_STDSEL, R3           ; R3: selected-state array
                MOVE    NT_REC, R5              ; R5: number of items
                ADD     OPTM_IR_SIZE, R5
                MOVE    @R5, R5
                XOR     R4, R4                  ; R4: flat index
_NT_SEL_1       MOVE    @R3++, R6
                CMP     0, R6                   ; selected?
                RBRA    _NT_SEL_2, Z            ; no
                MOVE    NT_S_SP, R8
                SYSCALL(puts, 1)
                MOVE    R4, R8
                SYSCALL(puthex, 1)
_NT_SEL_2       ADD     1, R4
                SUB     1, R5
                RBRA    _NT_SEL_1, !Z
                SYSCALL(crlf, 1)

_NT_SEL_RET     MOVE    R0, R8
                MOVE    R1, R9
                MOVE    R2, R10
                DECRB
                RET

                ; fatal callback: print the error code and stop
NT_FATAL        MOVE    R9, R0
                MOVE    NT_S_F, R8
                SYSCALL(puts, 1)
                MOVE    R0, R8
                SYSCALL(puthex, 1)
                SYSCALL(crlf, 1)
                SYSCALL(exit, 1)

